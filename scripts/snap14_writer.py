"""Write site/src/snap14.js in its lazy form (v0.39.1): the labs and the counts as a literal, the mind graph and the
engine's source as JSON strings parsed only when a desk first reads them. Half the page's bytes are these two, and
evaluating them as object literals cost every visitor 70 to 140 ms of boot (much more on a phone) for desks most never
open. The globals MIND_SNAP and CODE_SNAP keep their names: they are getters now.

    python3 scripts/snap14_writer.py          # rewrite the current snap14.js in the lazy form, data unchanged
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "site" / "src" / "snap14.js"


def write(snap14: dict, out: Path = OUT, header: str = "") -> Path:
    light = {k: v for k, v in snap14.items() if k not in ("mind", "code")}
    code = snap14.get("code") or []
    light["stats"] = {**light.get("stats", {}), "code_files": len(code), "code_lines": sum(int(f.get("lines") or 0) for f in code)}
    def enc(o):   # JSON text inside String.raw: no doubled escapes; the three sequences a template would read are JSON escapes
        t = json.dumps(o, separators=(",", ":"), ensure_ascii=False)
        t = t.replace("`", "\\u0060").replace("${", "$\\u007b").replace("</", "<\\/").replace("<!", "<\\u0021")
        t = re.sub(r"<(?=(?:html|head|body)\b)", r"\\u003c", t, flags=re.I)   # v0.42.5: source that holds "<!doctype" or "<html" is data; a scan of the page should not read it as a second document
        assert not t.endswith("\\")
        return "String.raw`" + t + "`"
    body = json.dumps(light, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    out.write_text(
        (header or "  /* snap14.js (generated by scripts/snapshot_v15.py through scripts/snap14_writer.py; do not edit): the labs, the unified\n"
                   "     mind and the engine's source for the code appendix. Derived results only. */\n")
        + f"  const SNAP14 = {body};\n"
        + f"  const SNAP14_MIND_JSON = {enc(snap14.get('mind'))};\n"
        + f"  const SNAP14_CODE_JSON = {enc(code)};\n"
        + "  (() => {      // parsed on first use, then kept\n"
        + "    let m = null, c = null;\n"
        + "    Object.defineProperty(SNAP14, \"mind\", { get: () => m || (m = JSON.parse(SNAP14_MIND_JSON)), enumerable: true });\n"
        + "    Object.defineProperty(SNAP14, \"code\", { get: () => c || (c = JSON.parse(SNAP14_CODE_JSON)), enumerable: true });\n"
        + "    Object.defineProperty(globalThis, \"MIND_SNAP\", { get: () => SNAP14.mind, configurable: true });\n"
        + "    Object.defineProperty(globalThis, \"CODE_SNAP\", { get: () => SNAP14.code, configurable: true });\n"
        + "  })();\n"
        + "  const LABS_SNAP = SNAP14.labs;\n")
    return out


def read(path: Path = OUT) -> dict:
    """Either form back into one dict (the eager form before v0.39.1, or the lazy one)."""
    t = path.read_text()
    snap = json.loads(re.search(r"const SNAP14 = (\{.*?\});\n", t, re.S).group(1))
    for k, var in (("mind", "SNAP14_MIND_JSON"), ("code", "SNAP14_CODE_JSON")):
        m = re.search(rf"const {var} = String\.raw`(.*?)`;\n", t, re.S)
        if m:
            snap[k] = json.loads(m.group(1))
        m = re.search(rf"const {var} = (\".*?\");\n", t, re.S)
        if m:
            snap[k] = json.loads(json.loads(m.group(1)))
    return snap


if __name__ == "__main__":
    s = read()
    write(s)
    print("snap14.js rewritten lazily:", OUT.stat().st_size // 1024, "KB;", len(s["mind"]["nodes"]), "nodes,", len(s["code"]), "files")
    sys.exit(0)
