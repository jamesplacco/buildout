"""Write site/src/sources.js (v0.36: the Reading room) from the curated source files in buildout/assets/sources/*.json.

Each file is a list of entries {title, who, date, type, url, claim, bears_on, changes, verified}: a paper, a dataset, a
book, a history, a podcast episode or a dissenting view, each checked by opening its page, each mapped to the theses
and desks it bears on and to what it changes. This script validates and merges them; it adds nothing.

    python3 scripts/snapshot_sources.py [--import DIR]   # --import copies DIR/*.json into the assets folder first
"""
from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "buildout" / "assets" / "sources"
TYPES = ("paper", "policy", "data", "book", "history", "longform", "podcast", "practitioner", "skeptic")
LANES = {"research": "Research and policy", "data": "Data that sees it first", "books": "Books, history and podcasts", "dissent": "The other side"}
BANNED = (chr(0x2014), chr(0x2013), "inter" "section", "load" "-bearing")
DESKS = {"desk", "book", "decision", "hedges", "options", "rates", "credit", "swans", "findings", "edges", "nowcast", "filings", "futures",
         "journal", "methods", "fundamentals", "positions", "insurers", "physics", "noteworthy", "digest"}


def clean(e: dict, lane: str) -> dict | None:
    req = ("title", "who", "date", "type", "url", "claim", "changes")
    if any(not str(e.get(k, "")).strip() for k in req) or not str(e["url"]).startswith(("https://", "http://")):
        return None
    out = {k: re.sub(r"\s+", " ", str(e[k])).strip() for k in req}
    for b in BANNED[:2]:
        for k in out:
            out[k] = out[k].replace(b, ", " if b == chr(0x2014) else " to ")
    if any(b in v.lower() for v in out.values() for b in BANNED[2:]):
        return None
    out["type"] = out["type"].lower() if out["type"].lower() in TYPES else "longform"
    out["bears_on"] = [x for x in (e.get("bears_on") or []) if re.fullmatch(r"t\d{1,2}", str(x)) or x in DESKS]
    out["lane"] = lane
    out["date"] = out["date"][:10]
    return out


def build() -> dict:
    rows, seen = [], set()
    for lane in LANES:
        p = ASSETS / f"{lane}.json"
        if not p.exists():
            continue
        for e in json.loads(p.read_text()):
            c = clean(e, lane)
            key = re.sub(r"[^a-z0-9]", "", c["title"].lower())[:60] if c else None
            if c and c["url"] not in seen and key not in seen:
                seen.update({c["url"], key})
                rows.append(c)
    rows.sort(key=lambda r: (list(LANES).index(r["lane"]), r["date"]), reverse=False)
    return {"lanes": LANES, "types": TYPES, "rows": rows, "n": len(rows)}


def main(argv: list[str]) -> None:
    if "--import" in argv:
        src = Path(argv[argv.index("--import") + 1])
        ASSETS.mkdir(parents=True, exist_ok=True)
        for lane in LANES:
            if (src / f"{lane}.json").exists():
                shutil.copy(src / f"{lane}.json", ASSETS / f"{lane}.json")
    S = build()
    s = json.dumps(S, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    (ROOT / "site" / "src" / "sources.js").write_text("  /* sources.js (v0.36, generated by scripts/snapshot_sources.py; do not edit): the Reading room. */\n"
                                                      f"  const SOURCES = {s};\n")
    print("sources.js", S["n"], "entries", {l: sum(r["lane"] == l for r in S["rows"]) for l in LANES})


if __name__ == "__main__":
    main(sys.argv[1:])
