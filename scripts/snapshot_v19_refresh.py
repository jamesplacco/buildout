"""Refresh site/src/snap19.js from a decision.json already built (v0.42.5), without rebuilding the mind.

    python3 -m buildout decide --out /tmp/dec
    python3 scripts/snapshot_v19_refresh.py /tmp/dec/decision.json

scripts/snapshot_v19.py rebuilds the mind as well, which takes far longer than the decision. The page's embedded
decision had fallen behind the published site/data/decision.json (same month, revised inputs), and nothing said so.
This keeps the embedded copy the same content as the published one; the page then also loads the published file
and prefers it when its content hash differs (boot.js).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from buildout import decide  # noqa: E402
from buildout.jsonout import clean  # noqa: E402


def main(argv: list[str]) -> None:
    src = json.loads(Path(argv[0]).read_text())
    out = ROOT / "site" / "src" / "snap19.js"
    old = out.read_text()
    i = old.index("const SNAP19 = ") + 15
    prev = json.loads(old[i:old.index(";\n", i)].replace("<\\/", "</"))["decision"]
    dec = clean({k: v for k, v in src.items() if k != "content_sha256"})
    dec["content_sha256"] = decide.content_hash(dec)
    assert dec.get("computed_utc"), "the decision file carries no computed_utc; build it with `python -m buildout decide`"
    if "v30_patch" in prev:
        dec["v30_patch"] = prev["v30_patch"]
    body = json.dumps({"decision": dec}, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    out.write_text("  /* snap19.js (v0.19, generated by scripts/snapshot_v19.py; do not edit): the decision engine, from data to a sized,\n"
                   "     explained decision, walked forward from 1940. Derived results only. */\n"
                   f"  const SNAP19 = {body};\n  const DX19 = SNAP19.decision;\n")
    print("snap19.js", len(body) // 1024, "KB; content", dec["content_sha256"], "; end", dec.get("end"))


if __name__ == "__main__":
    main(sys.argv[1:])
