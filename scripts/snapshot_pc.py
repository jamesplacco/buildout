"""Write site/src/snappc.js (v0.34: the private credit lens, Blue Owl at the centre) from buildout/private_credit.py.
Run `python3 scripts/snapshot_pc.py`, then `python3 scripts/assemble_page.py`. Every figure in the output is dated
and sourced in the module's OBS table; this script adds nothing."""
from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from buildout import private_credit as PC  # noqa: E402


def main(argv: list[str]) -> None:
    today = next((a.split("=", 1)[1] for a in argv if a.startswith("--date=")), date.today().isoformat())
    r = PC.report(today)
    r["findings"] = PC.summary(r)
    s = json.dumps({"credit": r}, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    (ROOT / "site" / "src" / "snappc.js").write_text("  /* snappc.js (v0.34, generated by scripts/snapshot_pc.py; do not edit): the private credit lens. Dated, sourced figures and the arithmetic on them. */\n"
                                                     f"  const SNAPPC = {s};\n")
    print("snappc.js", len(s) // 1024, "KB", "reds", r["reds"], "of", len(r["scorecard"]), "latest observation", r["latest_observation"])


if __name__ == "__main__":
    main(sys.argv[1:])
